#!/usr/bin/env python3
"""Generate an idempotent D1 import script from the legacy JSON files.

The source files are only read. The generated SQL is intentionally ignored by
git because it contains token hashes and event data.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def sql(value: str) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", type=Path, default=ROOT / "data")
    parser.add_argument("--output", type=Path, default=ROOT / "d1-import.sql")
    args = parser.parse_args()

    tokens_raw = json.loads((args.data_dir / "tokens.json").read_text(encoding="utf-8"))
    events_raw = json.loads((args.data_dir / "events.json").read_text(encoding="utf-8"))
    tokens = tokens_raw.get("tokens", {})
    bindings = tokens_raw.get("bindings", {})
    events = events_raw.get("events", []) if isinstance(events_raw, dict) else events_raw

    lines = ["-- Generated by tools/generate_d1_import.py", "PRAGMA foreign_keys = ON;"]
    for digest, record in tokens.items():
        lines.append(
            "INSERT OR IGNORE INTO tokens(token_hash, created_at, last_used_at) VALUES "
            f"({sql(digest)}, {sql(record.get('createdAt', ''))}, "
            f"{sql(record['lastUsedAt']) if record.get('lastUsedAt') else 'NULL'});"
        )
    for key, record in bindings.items():
        lines.append(
            "INSERT OR IGNORE INTO token_bindings(username_key, username, token_hash, created_at) VALUES "
            f"({sql(key.casefold())}, {sql(record.get('username', key))}, "
            f"{sql(record.get('token', ''))}, {sql(record.get('createdAt', ''))});"
        )
    for event in events:
        users = json.dumps(event.get("users") or [], ensure_ascii=False, separators=(",", ":"))
        lines.append(
            "INSERT OR IGNORE INTO events(id, name, description, starts_at, discord_url, users_json) VALUES "
            f"({sql(event['id'])}, {sql(event['name'])}, {sql(event.get('description') or '')}, "
            f"{sql(event['startsAt'])}, {sql(event['discordUrl'])}, {sql(users)});"
        )

    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Generated {args.output} ({len(tokens)} tokens, {len(bindings)} bindings, {len(events)} events).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
